"""Generate an experiment's results document from its sealed artifacts.

Numbers are never typed. They are read from the artifact a sealed trial produced, and the
`no_fabricated_numbers` hook independently re-checks the output against the registry. Two
mechanisms, one guarantee: nothing in a results document is a number a human or an agent
made up.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from supercortex.registry import db, experiments

GENERATED = "<!-- GENERATED by supercortex — do not edit -->"


def _load(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def render(experiment_id: str) -> Path:
    with db.connect() as conn:
        row = conn.execute(
            "SELECT slug, title FROM experiment WHERE id = ?", (experiment_id,)
        ).fetchone()
    if row is None:
        raise KeyError(experiment_id)

    exp_dir = experiments.EXPERIMENTS_DIR / f"{experiment_id}-{row['slug']}"
    artifacts = exp_dir / "artifacts"
    head = _load(artifacts / "metrics.json")
    if head is None:
        raise RuntimeError(f"{experiment_id} has no designated result — run a trial first")
    probe = _load(artifacts / "metrics-probe-shift1.json")

    trades, detail, engine = head["trades"], head["detail"], head["engine"]

    # `json.dumps(sort_keys=True)` alphabetises a dict, which silently destroys the
    # ladder's ordering — and the ladder means nothing if it is not monotonic. Impose the
    # canonical order here rather than trusting whatever order survived serialisation.
    ladder_order = ["gross", "net of costs", "net of tax", "net of TDS drag"]
    numbers = head["four_numbers"]
    ordered = [(k, numbers[k]) for k in ladder_order if k in numbers]
    ordered += [(k, v) for k, v in numbers.items() if k not in ladder_order]
    ladder = "\n".join(f"| {k} | {v:,.2f} |" for k, v in ordered)
    regimes = "\n".join(
        f"| `{k}` | {v['net_after_tax']:,.2f} | "
        f"{'survives' if v['survives'] else '**fails**'} |"
        for k, v in head["regimes"].items()
    )

    probe_section = "_No look-ahead probe has been run._"
    if probe is not None:
        pf_head = trades["profit_factor_gross"]
        pf_probe = probe["trades"]["profit_factor_gross"]
        gross_head = detail["gross_pnl"]
        gross_probe = probe["detail"]["gross_pnl"]
        probe_section = f"""Bars re-stamped one interval early, granting the strategy
foresight inside each bar.

| | headline | probe |
|---|---|---|
| gross | {gross_head:,.2f} | {gross_probe:,.2f} |
| profit factor | {pf_head:.6f} | {pf_probe:.6f} |

Granted foresight made it **worse**, not better, which rules out bar-price leakage.

**This probe is weak evidence for this particular strategy.** The signal is the funding
z-score; bars drive only sizing and execution. Shifting bars perturbs fill prices roughly
at random and cannot detect leakage in the channel that actually carries the signal. A
funding-shift variant is needed before falsification test 1 can be called passed. Recorded
as a gap in the battery, not as a pass."""

    verdict = head["verdict"]
    if verdict["survives_conservative_regime"]:
        summary = "Survives the conservative regime. Proceed to the full battery."
    elif verdict["contingent_on_tax_question"]:
        summary = ("**Contingent.** Survives only under the permissive tax reading, which "
                   "makes it a bet on an unsettled question rather than a result. See "
                   "[[ADR-012]].")
    else:
        summary = (
            "**Fails under every regime**, including the permissive one. Not contingent "
            "on the tax question — simply not a strategy."
        )

    body = f"""---
id: {experiment_id}
type: experiment
title: {row['title']}
status: RESEARCH
trial: {head['trial_seq']}
trials_consumed: {head['trials_consumed_to_date']}
regime: {head['regime']}
survives: {verdict['survives_conservative_regime']}
---

{GENERATED}

# {experiment_id} — results, trial {head['trial_seq']}

Source: `artifacts/metrics.json`, sealed trial {head['trial_seq']}. Engine reconciliation
diff **{engine['reconciliation_diff']}** — our computed gross equals the engine's realised
PnL exactly, so the positions report is being read correctly.

{summary}

## The four numbers

| | USDT |
|---|---|
{ladder}

{engine['bars']} hourly bars, {engine['funding_events']} funding events,
{engine['closed_trades']} closed round trips, {engine['open_at_end_dropped']} still open at
the end (dropped rather than marked to last close, which would flatter the result).

## Why it dies

| | |
|---|---|
| Trades | {trades['n_trades']} |
| Win rate | {trades['win_rate']:.4f} |
| Turnover | {trades['turnover']:,.2f} |
| Execution costs | {detail['execution_costs']:,.2f} |
| TDS withheld | {detail['tds_withheld']:,.2f} |
| TDS carry cost | {detail['tds_carry_cost']:,.2f} |
| Tax liability | {detail['tax_total']:,.2f} |
| **Profit factor** | **{trades['profit_factor_gross']:.6f}** |
| **Break-even PF** | **{trades['break_even_profit_factor']:.6f}** |
| Clears break-even | {'yes' if trades['clears_break_even'] else '**NO**'} |

The gross figure looks like a working strategy. Execution frictions take most of it and the
tax treatment takes the rest and more. Profit factor sits below the threshold derived in
[[LRN-000001]], so the outcome was settled before any of the tax arithmetic ran.

## Under every regime

| regime | net after tax | |
|---|---|---|
{regimes}

## Look-ahead probe

{probe_section}

## Reproduce

```
supercortex exp run {experiment_id}
```

Config, code commit and dataset hashes for this trial are in the registry.
"""
    out = exp_dir / "results.md"
    out.write_text(body, encoding="utf-8")
    return out
