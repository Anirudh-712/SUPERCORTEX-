"""The on-demand cockpit: collect facts, render Markdown, publish atomically.

What this is
------------
A *mirror*. `registry.sqlite` and the hashed dataset bytes are the sole authority; these
three pages are a derived, ignored, disposable view of them. A mirror necessarily restates
facts, so "no fact appears twice" is not claimed and is not achievable. What is guaranteed
is narrower and more useful: **nothing ever reads a fact back out of generated Markdown,
and no generated fact is copied into a hand-editable note.** Delete the whole thing and
`dash render` reconstructs it byte-for-byte.

Determinism
-----------
No clock is read anywhere. A dashboard that changes when nothing changed teaches its reader
to ignore it, so the only timestamps that appear are authoritative source values —
`lifecycle_event.at`, `dataset.verified_at`.

Two digests, kept distinct. `Snapshot.fingerprint` digests the **collected facts** and is
what each page header displays as "registry state". The generation **directory** is named
by `generation_address`, a digest of the **rendered page bytes** — see that function for
why addressing stored bytes by the facts alone was wrong.

Atomicity, stated honestly
--------------------------
Publication writes a complete generation under `.runtime/generations/<page-digest>/`,
then swaps a relative symlink with `os.replace`. The guarantee is **atomic visibility under
normal process interruption**: a reader sees the old generation or the new one, never a
half-written page.

It is *not* power-loss durability. That would require fsync of every file and of the
containing directories, and it is not implemented — so it is not claimed.

`os.replace` is never called with a directory as its destination. On macOS that raises
`ENOTEMPTY` against a non-empty directory, which would make an otherwise plausible design
work exactly once, on the first render.

What is deliberately absent
---------------------------
No trial artifact is ever opened. None of the three pages needs trial metrics, so the
artifact tree is not traversed and "missing artifact" is not a failure mode here. Dataset
Parquet bytes *are* hashed, because that verification is displayed.

Field contract for facts the registry cannot supply
---------------------------------------------------
`completeness` is **not shown, and not derived**. The authoritative registry contract has
no `completeness` and no `expected_rows` column, so there is nothing to read. Neither is it
reconstructed: rows, timestamps and interval would only produce an estimate, and
the producer stores a capped gap inventory, so `gaps_json` cannot yield a
missing-row total either — see `GAPS_CAVEAT` for how that figure is described.
The DATA card does carry a completeness figure, but a card is a
*generated mirror* — sourcing a fact from it would make this mirror depend on another
mirror rather than on the registry. `card_path` is therefore never collected at all.

Dataset *staleness* is **not classified**: the only configured threshold,
`data_staleness_seconds`, is a live-tick kill-switch bound and means nothing for an
archive-derived research dataset. Unknown lifecycle or falsification state renders as prose
naming what is unknown — never `0`, `N/A`, `TBD`, or a dash standing in for a value.
"""
from __future__ import annotations

import contextlib
import json
import os
import shutil
import sqlite3
import uuid
from collections.abc import Iterator
from dataclasses import asdict, dataclass
from pathlib import Path

import typer
from rich.console import Console

from supercortex import health
from supercortex.registry import db

#: Byte zero of every page. `guard_write.py` inspects only the first 200 bytes, so a marker
#: placed after YAML frontmatter is invisible to it — which is why these pages carry no
#: frontmatter at all.
MARKER = "<!-- GENERATED by supercortex — do not edit -->"

PAGES = ("attention.md", "pipeline.md", "evidence.md")

#: What the gap figure is, stated once. The producer caps its stored inventory, so this
#: is the number of gap entries the registry holds — not a guaranteed total inventory and
#: not a completeness percentage. The cap itself is deliberately not duplicated here: two
#: copies of a producer constant are two constants that will eventually disagree.
GAPS_CAVEAT = (
    "count of gap entries stored in the registry — not a completeness figure and not a "
    "guaranteed total inventory"
)

RUNTIME_DIRNAME = ".runtime"
GENERATIONS_DIRNAME = "generations"
LIVE_LINK = "generated"


class DashboardRefused(RuntimeError):
    """Rendering or publication refused. The previous dashboard is left untouched."""


# ── immutable snapshot ──────────────────────────────────────────────────────────
@dataclass(frozen=True)
class Verdict:
    test_name: str
    status: str
    ran_at: str


@dataclass(frozen=True)
class Experiment:
    id: str
    title: str
    status: str
    trial_budget: int
    trials_consumed: int
    trials_ok: int
    trials_abandoned: int
    trials_open: int
    over_budget: bool
    last_transition: str | None
    verdicts: tuple[Verdict, ...] = ()


@dataclass(frozen=True)
class Dataset:
    id: str
    title: str
    #: Nullable in the registry, so nullable here. `or ""` produced lines reading
    #: `series:   ()`, which states nothing while looking like a value.
    symbol: str | None
    interval: str | None
    kind: str | None
    rows: int | None
    start_ts: str | None
    end_ts: str | None
    gap_count: int | None
    verification: str          # "match" | "hash mismatch" | "file missing" | "no path recorded"


@dataclass(frozen=True)
class HealthCheck:
    name: str
    ok: bool
    detail: str


@dataclass(frozen=True)
class Snapshot:
    """Everything the three pages display, collected once and never mutated."""

    experiments: tuple[Experiment, ...] = ()
    datasets: tuple[Dataset, ...] = ()
    health: tuple[HealthCheck, ...] = ()

    @property
    def fingerprint(self) -> str:
        """Digest of the collected facts, shown in each page header as "registry state".

        Not the generation directory name: that is `generation_address`, over the rendered
        bytes. Moves only when the facts move.
        """
        return db.sha256_text(
            json.dumps(asdict(self), sort_keys=True, separators=(",", ":"))
        )


# ── collection: read-only, canonically ordered ──────────────────────────────────
@contextlib.contextmanager
def _open_readonly(registry: Path) -> Iterator[sqlite3.Connection]:
    """A read-only connection holding **one** snapshot for its whole lifetime.

    `mode=ro` stops writes; on its own it does nothing about *when* reads happen. Python's
    sqlite3 autocommits each SELECT, so successive queries can each observe a different
    committed version — a writer landing between them makes the result an interleaving of
    two registry states while still calling itself one immutable Snapshot.

    `isolation_level=None` hands transaction control here, and an explicit `BEGIN` opens a
    read transaction whose snapshot is fixed by the first query and held until rollback.
    Rollback rather than commit because nothing was written and nothing should look as
    though it was.
    """
    if not registry.exists():
        raise DashboardRefused(f"registry not found: {registry}")
    try:
        conn = sqlite3.connect(f"file:{registry}?mode=ro", uri=True, isolation_level=None)
    except sqlite3.Error as exc:
        raise DashboardRefused(f"registry cannot be opened: {exc}") from exc
    conn.row_factory = sqlite3.Row
    try:
        conn.execute("BEGIN")
        yield conn
    finally:
        try:
            conn.rollback()
        finally:
            conn.close()


def _verify_dataset(row: sqlite3.Row, project: Path) -> str:
    """Hash the registered Parquet against the registry. Resolves against `project`.

    Resolving a relative path against the global `db.PROJECT_ROOT` made a caller working
    on one tree silently consult another — wrong in production and untestable besides.
    """
    stored = row["parquet_path"]
    if not stored:
        return "no path recorded"
    path = Path(stored)
    if not path.is_absolute():
        path = project / path
    if not path.is_file():
        return "file missing"
    try:
        digest = db.sha256_file(path)
    except OSError:
        # Deliberately not the errno text: platform wording would vary the rendered bytes
        # by machine and defeat determinism, for no gain to the reader.
        return "file unreadable"
    return "match" if digest == row["sha256"] else "hash mismatch"


def _gap_count(raw: object, dataset_id: str) -> int | None:
    """Stored gap entries, or `None` when the registry never recorded any.

    Every branch that used to fall through to `0` now either refuses or reports the
    unknown as unknown. Silently turning malformed JSON into zero rendered a dataset as
    perfectly clean, which is the most costly direction for that error to point.
    """
    if raw is None:
        return None
    text = str(raw)
    if not text.strip():
        raise DashboardRefused(
            f"{dataset_id}: gaps_json is empty text rather than SQL NULL or a JSON list. "
            f"The gap inventory is neither absent nor present, so it cannot be rendered."
        )
    try:
        parsed = json.loads(text)
    except ValueError as exc:
        raise DashboardRefused(
            f"{dataset_id}: gaps_json is not valid JSON ({exc}). Refusing rather than "
            f"reporting an unknown gap inventory as zero."
        ) from exc
    if not isinstance(parsed, list):
        raise DashboardRefused(
            f"{dataset_id}: gaps_json holds a {type(parsed).__name__}, expected a JSON "
            f"list of gap entries."
        )
    return len(parsed)


def collect(*, registry: Path, project: Path) -> Snapshot:
    """Read every displayed fact once. Ordering is canonical, never SQLite's."""
    # `SchemaStatus.current` is the authoritative contract: it covers an unreadable
    # database and missing columns, indexes and triggers as well as missing tables.
    # Checking a hand-picked subset let a structurally broken registry produce pages that
    # read as authoritative.
    status = db.schema_status(registry)
    if not status.exists:
        raise DashboardRefused(f"registry not found: {registry}")
    if not status.current:
        raise DashboardRefused(status.summary())

    with _open_readonly(registry) as conn:
        try:
            summary = conn.execute("SELECT * FROM experiment_trials").fetchall()
            transitions = conn.execute(
                "SELECT entity_id, to_state, at FROM lifecycle_event"
            ).fetchall()
            verdicts = conn.execute(
                "SELECT experiment_id, test_name, status, passed, ran_at FROM falsification"
            ).fetchall()
            datasets = conn.execute("SELECT * FROM dataset").fetchall()
        except sqlite3.Error as exc:
            raise DashboardRefused(f"registry could not be read: {exc}") from exc

    latest: dict[str, sqlite3.Row] = {}
    for row in transitions:
        seen = latest.get(row["entity_id"])
        if seen is None or row["at"] > seen["at"]:
            latest[row["entity_id"]] = row

    by_experiment: dict[str, list[Verdict]] = {}
    for row in verdicts:
        # `status` is authoritative; a NULL predates the column and is not inferred from
        # `passed`, because a historical non-pass cannot be classified honestly.
        label = row["status"] or "recorded before verdicts were classified"
        by_experiment.setdefault(row["experiment_id"], []).append(
            Verdict(row["test_name"], label, row["ran_at"])
        )

    experiments = tuple(
        Experiment(
            id=row["id"],
            title=row["title"],
            status=row["status"],
            trial_budget=row["trial_budget"],
            trials_consumed=row["trials_consumed"] or 0,
            trials_ok=row["trials_ok"] or 0,
            trials_abandoned=row["trials_abandoned"] or 0,
            trials_open=row["trials_open"] or 0,
            over_budget=bool(row["over_budget"]),
            last_transition=(
                f"{latest[row['id']]['to_state']} at {latest[row['id']]['at']}"
                if row["id"] in latest else None
            ),
            verdicts=tuple(sorted(by_experiment.get(row["id"], []),
                                  key=lambda v: v.test_name)),
        )
        for row in sorted(summary, key=lambda r: str(r["id"]))
    )

    collected = tuple(
        Dataset(
            id=row["id"], title=row["title"], symbol=row["symbol"],
            interval=row["interval"], kind=row["kind"],
            rows=row["rows"], start_ts=row["start_ts"], end_ts=row["end_ts"],
            gap_count=_gap_count(row["gaps_json"], row["id"]),
            verification=_verify_dataset(row, project),
        )
        for row in sorted(datasets, key=lambda r: str(r["id"]))
    )

    checks = tuple(
        HealthCheck(c.name, c.ok, c.detail)
        for c in sorted(health.hook_checks(project), key=lambda c: c.name)
    )
    return Snapshot(experiments=experiments, datasets=collected, health=checks)


# ── rendering: pure, no I/O, no clock ───────────────────────────────────────────
def _head(title: str, fingerprint: str) -> list[str]:
    return [
        MARKER,
        "",
        f"# {title}",
        "",
        f"Generated by `supercortex dash render` from registry state `{fingerprint[:16]}`.",
        "Derived and disposable — the registry and hashed dataset bytes are authoritative.",
        "",
    ]


def _pipeline(snapshot: Snapshot) -> str:
    out = _head("Pipeline", snapshot.fingerprint)
    if not snapshot.experiments:
        out += ["No experiments registered.", ""]
        return "\n".join(out) + "\n"

    for exp in snapshot.experiments:
        out += [
            f"## {exp.id} — {exp.title}",
            "",
            f"- status: **{exp.status}**",
            f"- trials: {exp.trials_consumed} consumed of {exp.trial_budget} budgeted "
            f"({exp.trials_ok} ok, {exp.trials_abandoned} abandoned, "
            f"{exp.trials_open} unsealed)",
        ]
        out.append(
            f"- lifecycle: {exp.last_transition}" if exp.last_transition
            else "- lifecycle: no lifecycle transition recorded"
        )
        if exp.verdicts:
            for verdict in exp.verdicts:
                out.append(
                    f"- falsification `{verdict.test_name}`: {verdict.status} "
                    f"(ran {verdict.ran_at})"
                )
        else:
            out.append("- falsification: no falsification verdict recorded")
        out.append("")
    return "\n".join(out) + "\n"


def _or_not_recorded(value: str | None, field: str) -> str:
    """A nullable field says which field is missing, rather than rendering as nothing."""
    return value if value else f"{field} not recorded"


def _gaps_phrase(count: int | None) -> str:
    if count is None:
        return "gap inventory not recorded"
    return f"{count} gap entries recorded"


def _evidence(snapshot: Snapshot) -> str:
    out = _head("Evidence", snapshot.fingerprint)
    out += [
        "Coverage and hash verification for every registered dataset.",
        "",
        "**Completeness is not shown.** It is absent from the authoritative registry "
        "contract — there is no `completeness` and no `expected_rows` column — and it is "
        "not derived here from rows, timestamps, interval or gap inventory. The DATA "
        "cards carry a completeness figure, but a card is a generated mirror and is never "
        "read back. **Freshness is not classified:** no dataset-freshness threshold is "
        "configured.",
        "",
        f"Gap figures are a {GAPS_CAVEAT}.",
        "",
    ]
    if not snapshot.datasets:
        out += ["No datasets registered.", ""]
        return "\n".join(out) + "\n"

    for data in snapshot.datasets:
        rows = f"{data.rows:,}" if data.rows is not None else "row count not recorded"
        out += [
            f"## {data.id} — {data.title}",
            "",
            f"- series: {_or_not_recorded(data.symbol, 'symbol')} "
            f"{_or_not_recorded(data.interval, 'interval')} "
            f"({_or_not_recorded(data.kind, 'kind')})",
            f"- rows: {rows}",
            f"- coverage: {data.start_ts or 'start not recorded'} → "
            f"{data.end_ts or 'end not recorded'}",
            f"- gaps: {_gaps_phrase(data.gap_count)}",
            f"- hash verification: **{data.verification}**",
            "",
        ]
    return "\n".join(out) + "\n"


def _attention(snapshot: Snapshot) -> str:
    items: list[str] = []
    for exp in snapshot.experiments:
        if exp.over_budget:
            items.append(
                f"- {exp.id} is over budget: {exp.trials_consumed} trials consumed of "
                f"{exp.trial_budget} budgeted. Every extra trial inflates the "
                f"multiple-testing penalty."
            )
        if exp.trials_open:
            items.append(
                f"- {exp.id} has {exp.trials_open} unsealed trial(s). "
                f"`supercortex exp reap` if they are stale."
            )
        items += [
            f"- {exp.id} falsification `{v.test_name}` did not pass: {v.status} "
            f"(ran {v.ran_at})"
            for v in exp.verdicts if v.status.upper() not in {"PASS", "PASSED"}
        ]
    items += [
        f"- {d.id} dataset {d.verification}: the recorded bytes could not be confirmed."
        for d in snapshot.datasets if d.verification != "match"
    ]
    items += [
        f"- hook-enforcement health check failed — {c.name}: {c.detail}"
        for c in snapshot.health if not c.ok
    ]

    out = _head("Attention", snapshot.fingerprint)
    if items:
        out += ["Each line names something a human has to decide or repair.", ""]
        out += items
    else:
        out += ["Nothing requires a human. Empty is the good state."]
    out.append("")
    return "\n".join(out) + "\n"


def render(snapshot: Snapshot) -> dict[str, str]:
    """A completed snapshot to page bodies. Pure: no filesystem, no clock, no registry."""
    return {
        "attention.md": _attention(snapshot),
        "pipeline.md": _pipeline(snapshot),
        "evidence.md": _evidence(snapshot),
    }


# ── publication ─────────────────────────────────────────────────────────────────
def _swap_symlink(link: Path, target: Path, staging_root: Path) -> None:
    """Point `link` at `target` atomically, via a temporary link and `os.replace`.

    Deliberately never `os.replace(dir, dir)`: on macOS that raises ENOTEMPTY against a
    non-empty destination, so the obvious directory-rename design succeeds exactly once.
    """
    relative = os.path.relpath(target, link.parent)
    temporary = staging_root / f"link-{uuid.uuid4().hex[:8]}"
    os.symlink(relative, temporary)
    try:
        os.replace(temporary, link)
    except OSError:
        temporary.unlink(missing_ok=True)
        raise


def generation_address(pages: dict[str, str]) -> str:
    """Content address of the bytes actually stored.

    Deliberately a digest of the rendered pages, not of the snapshot. A generation
    directory holds rendered Markdown, so addressing it by the facts alone was wrong in a
    way that only showed up on the second change: alter the renderer and every stored
    generation looks inconsistent against a fresh render, and the command can never
    succeed again until someone deletes `.runtime/` by hand. Hashing what is stored makes
    a renderer change a new address, and leaves the inconsistency check to mean what it
    should — genuine collision or corruption.

    The pages already embed `Snapshot.fingerprint` in their header, so the facts are
    covered transitively and the reader still sees a registry-state digest.
    """
    return db.sha256_text(json.dumps(pages, sort_keys=True, separators=(",", ":")))


def _require_intact_generation(final: Path, pages: dict[str, str], address: str) -> None:
    """A generation is reused only if it is *entirely* what this code wrote.

    Checking the three expected files and stopping there let anything else in the
    directory ride along: an extra file added to a stored generation was published, and
    the live dashboard exposed four pages. The directory is what the symlink points at, so
    the whole directory is the unit that has to be intact — its entry set, each entry's
    type, and each entry's bytes.
    """
    entries = sorted(p.name for p in final.iterdir())
    if entries != sorted(PAGES):
        missing = sorted(set(PAGES) - set(entries))
        extra = sorted(set(entries) - set(PAGES))
        raise DashboardRefused(
            f"existing generation {address[:16]} does not hold exactly {list(PAGES)} — "
            f"missing {missing}, unexpected {extra}. Not reusing it and not moving the "
            f"live link."
        )
    for name, body in pages.items():
        existing = final / name
        if existing.is_symlink():
            raise DashboardRefused(
                f"existing generation {address[:16]}: {name} is a symlink, not a regular "
                f"file. Its bytes live outside the generation, so it is not reusable."
            )
        if not existing.is_file():
            raise DashboardRefused(
                f"existing generation {address[:16]}: {name} is not a regular file."
            )
        if existing.read_text(encoding="utf-8") != body:
            raise DashboardRefused(
                f"existing generation {address[:16]} is inconsistent: {name} differs from "
                f"a fresh render. Not reusing it and not moving the live link."
            )


def publish(pages: dict[str, str], dashboard_root: Path) -> Path:
    """Materialise a generation and make it the live one. Returns the generation path."""
    if set(pages) != set(PAGES):
        missing = sorted(set(PAGES) - set(pages))
        extra = sorted(set(pages) - set(PAGES))
        raise DashboardRefused(
            f"publication requires exactly the pages {list(PAGES)} — missing {missing}, "
            f"unexpected {extra}. Nothing has been written and the live link is unmoved."
        )

    link = dashboard_root / LIVE_LINK
    if link.exists() and not link.is_symlink():
        raise DashboardRefused(
            f"{link} exists and is not a symlink. Refusing to touch it — this command "
            f"never deletes a real directory. Move it aside and re-run."
        )

    address = generation_address(pages)
    runtime = dashboard_root / RUNTIME_DIRNAME
    generations = runtime / GENERATIONS_DIRNAME
    generations.mkdir(parents=True, exist_ok=True)
    final = generations / address

    if final.exists():
        _require_intact_generation(final, pages, address)
        _swap_symlink(link, final, runtime)
        return final

    staging = runtime / f"staging-{uuid.uuid4().hex[:8]}"
    try:
        staging.mkdir(parents=True)
        for name, body in pages.items():
            (staging / name).write_text(body, encoding="utf-8")
        # Rename into place only once every page is complete on disk. The destination
        # does not exist, so this is a plain rename, never a directory overwrite.
        os.replace(staging, final)
        _swap_symlink(link, final, runtime)
    finally:
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)
    return final


def render_dashboard(*, registry: Path, project: Path, dashboard_root: Path) -> Path:
    """Collect, render, publish. Nothing is written until the snapshot is complete."""
    snapshot = collect(registry=registry, project=project)
    pages = render(snapshot)
    return publish(pages, dashboard_root)


# ── command line ────────────────────────────────────────────────────────────────
app = typer.Typer(no_args_is_help=True, help="On-demand cockpit.")
console = Console()


@app.command("render")
def render_command() -> None:
    """Regenerate the cockpit from registry state. Read-only; output is gitignored.

    Writes nothing outside `00-dashboard/.runtime/`, touches neither the registry nor any
    artifact, and publishes by swapping a symlink so a reader sees the previous dashboard
    or the new one, never a half-written page.
    """
    try:
        generation = render_dashboard(
            registry=db.DB_PATH,
            project=db.PROJECT_ROOT,
            dashboard_root=db.PROJECT_ROOT / "00-dashboard",
        )
    except DashboardRefused as refusal:
        console.print(f"[red]dash render refused[/] — {refusal}", soft_wrap=True)
        raise typer.Exit(1) from refusal

    link = db.PROJECT_ROOT / "00-dashboard" / LIVE_LINK
    console.print(f"[green]cockpit rendered[/] {link.relative_to(db.PROJECT_ROOT)}")
    console.print(f"generation {generation.name[:16]}")
    for name in PAGES:
        console.print(f"  {(link / name).relative_to(db.PROJECT_ROOT)}")
