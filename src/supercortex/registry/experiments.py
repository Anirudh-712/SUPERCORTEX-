EXPERIMENTS_DIR = PROJECT_ROOT / "02-experiments"

def dump_metrics(metrics: dict[str, Any]) -> str:
    """Render a metrics artifact. The ONLY place its serialization settings are stated.

    `allow_nan=False` is the load-bearing one: json.dumps otherwise emits bare `NaN` and
    `Infinity`, which are not JSON. The artifact would look sealed and no conforming
    parser could read it. `backtest.trial` runs this same function as a pre-flight inside
    the guarded region, so a document cannot pass validation and then fail the writer.
    """
    return json.dumps(metrics, indent=2, sort_keys=True, allow_nan=False)
GENERATED = "<!-- GENERATED by supercortex — do not edit -->"


def slugify(title: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return slug[:60] or "untitled"


@dataclass(frozen=True)
class Experiment:
    id: str
    title: str
    slug: str
    trial_budget: int

    @property
    def dir(self) -> Path:
        return EXPERIMENTS_DIR / f"{self.id}-{self.slug}"


def register(title: str, trial_budget: int, owner_agent: str | None = None) -> Experiment:
    """Create an experiment: a registry row, a folder, and a pre-registration stub.

    The hypothesis stub is created empty *and committed* before any trial can run, so
    git history proves the hypothesis predates the results.
    """
    with connect() as conn:
        exp_id = allocate_id(conn, "EXP")
        slug = slugify(title)
        conn.execute(
            "INSERT INTO experiment(id, title, slug, status, trial_budget, created_at, owner_agent)"
            " VALUES (?,?,?,?,?,?,?)",
            (exp_id, title, slug, "RESEARCH", trial_budget, now(), owner_agent),
        )
    exp = Experiment(exp_id, title, slug, trial_budget)
    _scaffold(exp)
    return exp


def _scaffold(exp: Experiment) -> None:
    (exp.dir / "artifacts").mkdir(parents=True, exist_ok=True)
    front = (
        f"---\nid: {exp.id}\ntype: experiment\ntitle: {exp.title}\n"
        f"status: RESEARCH\ncreated: {now()[:10]}\ntrial_budget: {exp.trial_budget}\n"
        f"trials_consumed: 0\nfalsification_verdict: null\ntags: []\n---\n\n"
    )
    stubs = {
        "hypothesis.md": front
        + "# Hypothesis\n\n## Claim\n\n_State the effect in one sentence._\n\n"
        "## Mechanism\n\n_Who is forced to trade, and why?_\n\n"
        "## Falsifier\n\n_What observation would prove this wrong?"
        " Name it now, before results exist._\n\n"
        "## Universe and period\n\n_Declared up front. Changing these later"
        " is selection bias._\n",
        "methodology.md": front + "# Methodology\n\n_Data, features, entry/exit, sizing._\n",
        "decision.md": front + "# Decision\n\n_Written by the CIO after falsification._\n",
    }
    for name, body in stubs.items():
        path = exp.dir / name
        if not path.exists():
            path.write_text(body, encoding="utf-8")
    config = exp.dir / "config.yaml"
    if not config.exists():
        config.write_text(
            f"# {exp.id} — the ONLY source of parameters.\n"
            "# Never pass a parameter on the command line: it would not be hashed,\n"
            "# and the trial would not be reproducible.\n"
            f"experiment_id: {exp.id}\nstrategy: null\nseed: 42\n\nparams: {{}}\n\n"
            "data:\n  datasets: []\n\ncost_model:\n  version: india-vda-1.0.0\n",
            encoding="utf-8",
        )


def _hypothesis_committed(exp_dir: Path) -> bool:
    """Pre-registration check: is hypothesis.md in git history?"""
    rel = (exp_dir / "hypothesis.md").relative_to(PROJECT_ROOT).as_posix()
    result = subprocess.run(
        ["git", "log", "--diff-filter=A", "--format=%H", "--", rel],
        cwd=PROJECT_ROOT, capture_output=True, text=True,
    )
    return bool(result.stdout.strip())


def open_trial(
    experiment_id: str,
    *,
    config_text: str,
    data_snapshot: str,
    cost_model_version: str,
    seed: int,
    agent_id: str | None = None,
    note: str | None = None,
    strict: bool = True,
) -> int:
    """Record a trial BEFORE it runs. Returns the sequence number.

    This is the chokepoint. Every backtest passes through here or the trial count —
    and therefore every significance test built on it — is a lie.
    """
    with connect() as conn:
        row = conn.execute("SELECT slug FROM experiment WHERE id = ?", (experiment_id,)).fetchone()
        if row is None:
            raise KeyError(f"unknown experiment {experiment_id}")
        exp_dir = EXPERIMENTS_DIR / f"{experiment_id}-{row['slug']}"

        if strict and not _hypothesis_committed(exp_dir):
            raise RuntimeError(
                f"{experiment_id}: hypothesis.md is not yet in git history. Pre-registration "
                "means the hypothesis is committed BEFORE the first trial runs. Commit it."
            )

        # The experiment's own config and strategy are inputs too — they must be committed.
        exp_rel = exp_dir.relative_to(PROJECT_ROOT).as_posix()
        commit = git_commit(
            strict=strict,
            extra_inputs=(f"{exp_rel}/config.yaml", f"{exp_rel}/strategy.py"),
        )
        seq = (
            conn.execute(
                "SELECT COALESCE(MAX(seq), 0) + 1 AS n FROM trial WHERE experiment_id = ?",
                (experiment_id,),
            ).fetchone()["n"]
        )
        conn.execute(
            "INSERT INTO trial(experiment_id, seq, config_hash, code_commit, data_snapshot,"
            " cost_model_version, seed, started_at, agent_id, note)"
            " VALUES (?,?,?,?,?,?,?,?,?,?)",
            (experiment_id, seq, sha256_text(config_text), commit, data_snapshot,
             cost_model_version, seed, now(), agent_id, note),
        )
    return int(seq)


#: The verdict strings this table stores. The registry owns storage, not meaning, so it
#: declares its own accepted set rather than importing the falsify package - that import
#: would run registry -> falsify -> registry and close a cycle. A drift test asserts this
#: set equals the union of `BatteryStatus` and `ChannelStatus`.
FALSIFICATION_STATUSES = ("PASS", "FAIL", "SUSPICIOUS", "INERT", "UNDEFINED")

#: What a NULL status means, named so no reader has to decide for itself. A row written
#: before the column existed cannot be classified: `passed = 0` does not say which kind of
#: non-pass it was, and `statistic IS NULL` is ambiguous because a real test can
#: legitimately have no statistic. Such a row is evidence of nothing and must never
#: satisfy a lifecycle gate.
LEGACY_UNCLASSIFIED = None


def record_falsification(
    experiment_id: str,
    test_name: str,
    *,
    status: str,
    statistic: float | None,
    threshold: float | None,
    trials_at_run: int,
    artifact_path: str | None = None,
    ran_at: str | None = None,
) -> None:
    """Record one falsification verdict. The only sanctioned writer of this table.

    `passed` is DERIVED from the status rather than accepted beside it: a caller that can
    supply both can supply a pair that disagree, and the row would then say two things at
    once. Every mutable field is replaced on a rerun - leaving a stale threshold or
    artifact path beside a fresh verdict would attribute the new result to the old bar.
    """
    if status is None or status not in FALSIFICATION_STATUSES:
        raise ValueError(
            f"status {status!r} is not one of {list(FALSIFICATION_STATUSES)}; a verdict "
            f"is recorded as what it was, never as a bare pass/fail"
        )
    passed = int(status == "PASS")
    with connect() as conn:
        conn.execute(
            "INSERT INTO falsification(experiment_id, test_name, statistic, threshold,"
            " status, passed, ran_at, artifact_path, trials_at_run)"
            " VALUES (?,?,?,?,?,?,?,?,?)"
            " ON CONFLICT(experiment_id, test_name) DO UPDATE SET"
            " statistic=excluded.statistic, threshold=excluded.threshold,"
            " status=excluded.status, passed=excluded.passed, ran_at=excluded.ran_at,"
            " artifact_path=excluded.artifact_path,"
            " trials_at_run=excluded.trials_at_run",
            (experiment_id, test_name, statistic, threshold, str(status), passed,
             ran_at or now(), artifact_path, trials_at_run),
        )


def close_trial(
    experiment_id: str,
    seq: int,
    outcome: str,
    metrics: dict[str, Any] | None = None,
    *,
    is_headline: bool = True,
) -> Path | None:
    """Seal a trial. After this the row is immutable — the triggers enforce it."""
    if outcome not in {"ok", "error", "abandoned"}:
        raise ValueError(f"invalid outcome {outcome!r}")

    metrics_path: Path | None = None
    artifact_sha256: str | None = None
    if metrics is not None:
        with connect() as conn:
            slug = conn.execute(
                "SELECT slug FROM experiment WHERE id = ?", (experiment_id,)
            ).fetchone()["slug"]
        artifacts = EXPERIMENTS_DIR / f"{experiment_id}-{slug}" / "artifacts"
        artifacts.mkdir(parents=True, exist_ok=True)
        payload = dump_metrics(metrics)
        # The digest covers the bytes that land on disk, not a re-serialisation of the
        # dict: the file is what a later reader authenticates.
        encoded = payload.encode("utf-8")
        artifact_sha256 = hashlib.sha256(encoded).hexdigest()
        metrics_path = artifacts / f"metrics-trial-{seq:04d}.json"
        metrics_path.write_bytes(encoded)
        # metrics.json is the DESIGNATED result, not merely the most recent one. A
        # diagnostic probe deliberately corrupts its own inputs, so letting it overwrite
        # the headline would leave the experiment reporting a number produced by a run
        # that was never meant to be believed.
        if is_headline:
            (artifacts / "metrics.json").write_bytes(encoded)

    with connect() as conn:
        conn.execute(
            "UPDATE trial SET finished_at = ?, outcome = ?, metrics_path = ?,"
            " artifact_sha256 = ? WHERE experiment_id = ? AND seq = ?",
            (now(), outcome,
             metrics_path.relative_to(PROJECT_ROOT).as_posix() if metrics_path else None,
             artifact_sha256, experiment_id, seq),
        )
    return metrics_path


def reap_stale(max_age_hours: float = 6.0) -> list[tuple[str, int]]:
    """Mark long-open trials as abandoned. They still count. That is the point."""
    cutoff_expr = f"-{max_age_hours} hours"
    with connect() as conn:
        rows = conn.execute(
            "SELECT experiment_id, seq FROM trial WHERE finished_at IS NULL"
            " AND started_at < datetime('now', ?)",
            (cutoff_expr,),
        ).fetchall()
        for row in rows:
            conn.execute(
                "UPDATE trial SET finished_at = ?, outcome = 'abandoned'"
                " WHERE experiment_id = ? AND seq = ?",
                (now(), row["experiment_id"], row["seq"]),
            )
    return [(r["experiment_id"], r["seq"]) for r in rows]


def trial_count(experiment_id: str) -> int:
    """The N that feeds the Deflated Sharpe Ratio."""
    with connect() as conn:
        row = conn.execute(
            "SELECT COUNT(*) AS n FROM trial WHERE experiment_id = ?", (experiment_id,)
        ).fetchone()
    return int(row["n"])


def summary() -> list[sqlite3.Row]:
    with connect() as conn:
        return conn.execute("SELECT * FROM experiment_trials ORDER BY id").fetchall()
